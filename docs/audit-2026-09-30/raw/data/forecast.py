# Оценка по коду: на визит читается вся коллекция products + мелкие коллекции (~21 док, ~17 КБ)
READ_PRICE=0.03/100000   # USD за чтение, us-central1, без бесплатной квоты (именованная база)
EGRESS=0.12              # USD/ГиБ, 10-1024 ГиБ, Worldwide
GiB=2**30
small_docs=21; small_kb=17
print("товаров | визитов/день | фото | чтений/мес | $ чтения | ГиБ/мес | $ трафик (без 10 ГиБ / с 10 ГиБ free) | МБ на визит")
for n in (7,100,1000,5000):
  for v in (100,1000):
    for label,kb in (("base64 ~520 КБ",520),("без фото ~5 КБ",5)):
      reads=v*30*(n+small_docs); mb=(n*kb+small_kb)/1000
      gib=v*30*(n*kb+small_kb)*1000/GiB
      print(f"{n:5} | {v:5} | {label} | {reads:>12,} | {reads*READ_PRICE:8.2f} | {gib:10,.1f} | {gib*EGRESS:9,.0f} / {max(0,gib-10)*EGRESS:9,.0f} | {mb:8,.1f}")
# лимит документа: заказ с k строками одного товара
LIM=1048576
for kb_unit in (1000,1024):
  for k in (1,2,3):
    size=k*521*kb_unit+3000
    print(f"заказ {k} строк(и) товара 521 КБ (1 КБ={kb_unit} Б): {size:,} Б -> {'ПРЕВЫШЕН' if size>LIM else 'ok'} (лимит {LIM:,})")
# фото в товаре
for ph in (120,171,250,400):
  print(f"фото {ph} КБ base64: в товар (1 МиБ, ~8 КБ на остальное) входит {int((LIM-8000)/(ph*1024))} фото")
